#!/usr/bin/env node
/*
 * Builds public/cmhc/mmg-dashboard.html from the business's MMG dashboard HTML (v7 or later).
 *
 *   node tools/cmhc/build-v7-host.mjs "<path to MMG-Dashboard vN.html>"
 *
 * The dashboard is a single-file app. KingSight shows it unchanged inside the CMHC Dashboard page (an iframe on
 * the same origin) so every screen, calculation and interaction stays exactly as the business built it. This
 * script only re-plumbs the file:
 *   - the dataset baked into the file is removed: the page loads the live, role-filtered pipeline from KingSight
 *     (public/cmhc/cmhc-host.js);
 *   - the file's saved settings keep only team configuration (scoring weights, vacations, ...). Anything that
 *     carries loan data (history, renewals, FFA, per-deal marks) is removed: it comes from the API, filtered by
 *     role, so the static page never holds loan data;
 *   - the file's own storage script (restore) is replaced by cmhc-host.js, which routes the report's
 *     localStorage through KingSight (shared team settings are saved to the API);
 *   - cmhc-host.css hides the standalone header, upload screens and "New data" (KingSight provides the menu).
 *
 * When the business sends a new version, run this again with the new file.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..', '..');
const OUT = resolve(repo, 'public/cmhc/mmg-dashboard.html');

const input = process.argv[2];
if (!input) {
  console.error('Usage: node tools/cmhc/build-v7-host.mjs "<dashboard.html>"');
  process.exit(1);
}

let html = readFileSync(input, 'utf8');
// Bundled exports keep the page as a JSON string in a template block.
const bundled = /<script type="__bundler\/template">\s*([\s\S]*?)\s*<\/script>/.exec(html);
if (bundled) html = JSON.parse(bundled[1]);

/** Saved settings that are team configuration only, no loan data. Everything else in file-state is dropped. */
const CONFIG_KEYS = new Set([
  'cmhc_alloc_weights_v1',
  'cmhc_alloc_weights_default_v1',
  'cmhc_alloc_francophones_v1',
  'cmhc_alloc_coverage_v1',
  'cmhc_alloc_locked_v1',
  'cmhc_alloc_locked_v1_coi2',
  // Keyed by loan code only (no names or amounts): each file's language and active/inactive marks.
  'cmhc_alloc_deal_language_v1',
  'cmhc_alloc_active_v1',
  'cmhc_alloc_active_reset_v1',
  'cmhc_tl_hidden_v2',
  'mmg_rev_vac_v1',
  'mmg_revcal_cap',
  'mmg_wip_view',
  'mmg_ren_ms_v1',
]);

const fail = (msg) => {
  console.error('build-v7-host: ' + msg);
  process.exit(1);
};
const replaceOnce = (re, fn, what) => {
  let n = 0;
  html = html.replace(re, (...m) => {
    n++;
    return fn(...m);
  });
  if (n !== 1) fail(`expected exactly one ${what}, found ${n}`);
};

// 1. Saved settings: team configuration only.
const kept = [];
const dropped = [];
replaceOnce(
  /(<script id="file-state" type="application\/json">)([\s\S]*?)(<\/script>)/,
  (_, open, body, close) => {
    const fs = JSON.parse(body.trim() || 'null') || {};
    const settings = {};
    for (const [k, v] of Object.entries(fs.settings || {})) {
      if (CONFIG_KEYS.has(k)) {
        settings[k] = v;
        kept.push(k);
      } else dropped.push(`${k} (${v.length} chars)`);
    }
    const json = JSON.stringify({ savedAt: fs.savedAt || null, settings }).replace(/</g, '\\u003c');
    return open + json + close;
  },
  'file-state block',
);

// 2. The file's storage script → KingSight's host bridge (must run before the report's code).
replaceOnce(
  /<script>\s*\/\* The file always wins on first open[\s\S]*?<\/script>/,
  () => '<script src="cmhc-host.js"></script>',
  'restore script',
);

// 3. No baked-in dataset: the live pipeline is loaded by the host.
replaceOnce(
  /(<script id="embedded-dataset" type="application\/json">)[\s\S]*?(<\/script>)/,
  (_, open, close) => open + close,
  'embedded dataset',
);

// 4. Host styles; once the report has booted, the host loads the live pipeline.
replaceOnce(/<\/head>/, () => '<link rel="stylesheet" href="cmhc-host.css">\n</head>', '</head>');
const lastScript = html.lastIndexOf('</script>');
if (lastScript < 0) fail('no app script');
html =
  html.slice(0, lastScript + 9) +
  '\n<script>window.__cmhcHostStart && window.__cmhcHostStart();</script>' +
  html.slice(lastScript + 9);

const banner = `<!-- Generated by tools/cmhc/build-v7-host.mjs from ${basename(input)} on ${new Date().toISOString().slice(0, 10)}. Do not edit; re-run the script. -->\n`;
mkdirSync(dirname(OUT), { recursive: true });
// The comment goes after the doctype: anything before it would switch the page to quirks mode.
const doctype = /^\s*<!doctype[^>]*>\s*/i.exec(html);
writeFileSync(OUT, doctype ? doctype[0] + banner + html.slice(doctype[0].length) : banner + html);

console.log(`Wrote ${OUT} (${(html.length / 1024).toFixed(0)} KB)`);
console.log(`Settings kept: ${kept.join(', ') || 'none'}`);
console.log(`Settings dropped (loan data or per-browser): ${dropped.join(', ') || 'none'}`);
